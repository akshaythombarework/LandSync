// Build fast normalized lowercase lookup maps
const normalizedDictionaries: Record<Language, Map<string, string>> = {
  en: new Map(),
  hi: new Map(),
  mr: new Map()
};

for (const lang of ['hi', 'mr'] as Language[]) {
  const dict = translations[lang];
  for (const [key, val] of Object.entries(dict)) {
    if (val && typeof val === 'string') {
      normalizedDictionaries[lang].set(key.toLowerCase().trim(), val);
    }
  }
}

// Pre-sorted phrase keys by length descending for greedy phrase replacement
const sortedPhraseKeys: Record<Language, Array<{ eng: string; trans: string; regex: RegExp }>> = {
  en: [],
  hi: [],
  mr: []
};

for (const lang of ['hi', 'mr'] as Language[]) {
  const pairs: Array<{ eng: string; trans: string; regex: RegExp }> = [];
  const dict = translations[lang];
  for (const [key, trans] of Object.entries(dict)) {
    if (key.length >= 3 && trans && key !== trans) {
      // Escape special regex characters in English string
      const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      pairs.push({
        eng: key,
        trans,
        regex: new RegExp(`\\b${escaped}\\b`, 'gi')
      });
    }
  }
  // Sort longest phrases first so "Total Documents" matches before "Total"
  pairs.sort((a, b) => b.eng.length - a.eng.length);
  sortedPhraseKeys[lang] = pairs;
}

/**
 * High-performance string translator with exact match, normalized lookup,
 * regex pattern recognition, and multi-word phrase replacement.
 */
export function translateText(rawText: string, lang: Language): string {
  if (!rawText || lang === 'en') return rawText;

  // Extract leading and trailing whitespace to preserve formatting
  const match = rawText.match(/^(\s*)([\s\S]*?)(\s*)$/);
  if (!match) return rawText;

  const [, leadingSpace, coreText, trailingSpace] = match;
  if (!coreText || !/[a-zA-Z]/.test(coreText)) {
    return rawText;
  }

  const langDict = translations[lang];

  // 1. Exact match in dictionary
  if (langDict[coreText]) {
    return leadingSpace + langDict[coreText] + trailingSpace;
  }

  // 2. Case-insensitive / trimmed match
  const lowerCore = coreText.toLowerCase().trim();
  const normalizedMatch = normalizedDictionaries[lang].get(lowerCore);
  if (normalizedMatch) {
    return leadingSpace + normalizedMatch + trailingSpace;
  }

  // 3. Dynamic Pattern Matching for common government UI patterns
  // Pattern: "Showing X of Y Submissions"
  const showingMatch = coreText.match(/^Showing\s+(\d+)\s+of\s+(\d+)\s+Submissions$/i);
  if (showingMatch) {
    const [, x, y] = showingMatch;
    if (lang === 'hi') return `${leadingSpace}प्रदर्शित ${x} कुल ${y} प्रस्तुत आवेदन${trailingSpace}`;
    if (lang === 'mr') return `${leadingSpace}दर्शवित आहे ${x} पैकी ${y} सादर अर्ज${trailingSpace}`;
  }

  // Pattern: "Survey No: X" or "Survey No.: X"
  const surveyMatch = coreText.match(/^Survey\s*No\.?:?\s*(.*)$/i);
  if (surveyMatch) {
    const num = surveyMatch[1];
    if (lang === 'hi') return `${leadingSpace}सर्वे क्र: ${num}${trailingSpace}`;
    if (lang === 'mr') return `${leadingSpace}सर्व्हे क्र: ${num}${trailingSpace}`;
  }

  // Pattern: "Area: X"
  const areaMatch = coreText.match(/^Area:\s*(.*)$/i);
  if (areaMatch) {
    const a = areaMatch[1];
    if (lang === 'hi') return `${leadingSpace}क्षेत्रफल: ${a}${trailingSpace}`;
    if (lang === 'mr') return `${leadingSpace}क्षेत्र: ${a}${trailingSpace}`;
  }

  // 4. Multi-word phrase greedy substitution
  let translatedCore = coreText;
  let replacedAny = false;
  const phraseList = sortedPhraseKeys[lang];

  for (let i = 0; i < phraseList.length; i++) {
    const { regex, trans } = phraseList[i];
    if (regex.test(translatedCore)) {
      translatedCore = translatedCore.replace(regex, trans);
      replacedAny = true;
      // Reset regex lastIndex
      regex.lastIndex = 0;
    }
  }

  if (replacedAny) {
    return leadingSpace + translatedCore + trailingSpace;
  }

  return rawText;
}
